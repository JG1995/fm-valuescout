#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    fn dump_key_set() -> HashSet<&'static str> {
        DUMP_ATTRIBUTE_KEYS.iter().copied().collect()
    }

    #[test]
    fn catalog_is_non_empty() {
        assert!(!all_roles().is_empty());
    }

    #[test]
    fn role_ids_are_unique() {
        let mut seen = HashSet::new();
        for role in all_roles() {
            assert!(
                seen.insert(role.role_id),
                "duplicate role_id: {}",
                role.role_id
            );
        }
    }

    #[test]
    fn every_role_has_non_empty_primary_from_dump_keys() {
        let dump = dump_key_set();
        for role in all_roles() {
            assert!(
                !role.primary.is_empty(),
                "{} has empty primary",
                role.role_id
            );
            for key in role.primary.iter().chain(role.secondary.iter()) {
                assert!(
                    dump.contains(key),
                    "{} uses unknown attribute key {}",
                    role.role_id,
                    key
                );
            }
        }
    }

    #[test]
    fn every_role_has_valid_phase() {
        for role in all_roles() {
            match role.phase {
                RolePhase::InPossession | RolePhase::OutOfPossession => {}
            }
            let suffix_ok = role.role_id.ends_with("_ip") || role.role_id.ends_with("_oop");
            assert!(suffix_ok, "role_id should end _ip/_oop: {}", role.role_id);
            let expects_ip = role.role_id.ends_with("_ip");
            assert_eq!(
                expects_ip,
                role.phase == RolePhase::InPossession,
                "phase mismatch for {}",
                role.role_id
            );
        }
    }

    #[test]
    fn label_map_covers_catalog_transcription_labels() {
        assert_eq!(label_to_dump_key("Jumping"), Some("JumpingReach"));
        assert_eq!(label_to_dump_key("Off the Ball"), Some("OffTheBall"));
        assert_eq!(label_to_dump_key("Team Work"), Some("Teamwork"));
        assert_eq!(label_to_dump_key("One on Ones"), Some("OneOnOnes"));
        assert_eq!(label_to_dump_key("not a real attr"), None);
    }

    #[test]
    fn primary_and_secondary_bands_are_disjoint() {
        for role in all_roles() {
            let primary: HashSet<_> = role.primary.iter().copied().collect();
            for key in role.secondary {
                assert!(
                    !primary.contains(key),
                    "{} lists {} in both primary and secondary",
                    role.role_id,
                    key
                );
            }
        }
    }

    #[test]
    fn deep_lying_playmaker_has_expected_primary_band() {
        let role = all_roles()
            .iter()
            .find(|r| r.role_id == "deep_lying_playmaker_ip")
            .expect("deep_lying_playmaker_ip");
        assert_eq!(role.phase, RolePhase::InPossession);
        assert!(role.primary.contains(&"Passing"));
        assert!(role.primary.contains(&"Vision"));
        assert!(role.primary.contains(&"OffTheBall"));
        assert!(!role.secondary.contains(&"OffTheBall"));
        assert!(!role.secondary.is_empty());
    }
}
